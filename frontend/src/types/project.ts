/**
 * 项目。
 *
 * **正文这次留在 TS 里，没有再走 Markdown。**
 * 从前正文放在 `content/projects/<slug>.md`，由 markdown-it 渲染 ——
 * 那套渲染器随 `/notes` 一起删掉了，站上暂时没有 Markdown 管线，
 * 而且项目正文本身是**结构化**的（一句引子 + 一段正文 + 一句旁白），
 * 写成字段比写 md 再解析更省事，也少两个依赖。
 * 哪天正文长到需要自由排版（代码块、任意嵌套），再连渲染器一起引回来。
 */

/**
 * 一段视频。
 *
 * **详情页唯一的媒体，一页最多一段。**
 *
 * 这一页原本的规矩是「无图无卡」：只有字、留白和细线，靠透明度分层级。
 * 上一个项目（RAT-LLM）的案例页里那些 SVG 信号图与彩色条形图都没有搬进来 ——
 * 它们是「好看」，不是「证据」，文字说得清。
 * 无人机这个不一样：那 8 秒画面本身就是项目的证据（双向高架被分成独立区域、
 * 框住的车在动、density 在跳），拿一段话替不掉。所以开这一个口子。
 *
 * **判据是「不放就说不清」**，不是「有素材」。装饰性的图、logo、截图
 * 一律不要 —— 一旦这页开始放好看的图，它就从「读数的地方」变成了作品集。
 */
export interface ProjectVideo {
  /** 视频地址。资源放 `src/assets/projects/`，在数据文件里 import 进来 */
  src: string
  /**
   * 封面（第一帧）。不设就是一片黑，等元数据加载完才出画面 ——
   * 这一页素得很，一块黑突兀，所以能设就设。
   */
  poster?: string
  /** 视频**下面**那行说明（表的 caption 在上面，两者的位置刻意相反） */
  caption?: string
}

/**
 * 一条通路：按顺序推进的若干阶段，每个阶段里可以并排放几件事。
 *
 * **只在「流向本身就是内容」时才用。** 判据和表、视频是同一条 ——
 * 「主进程写入图像帧 → 共享内存 → 三个计算进程并行取用 → 后处理按帧编号汇合」
 * 写成一句话读得懂，但「谁在谁下游、哪几件事是同时发生的」读不出来，
 * 而这正是那一节要讲的东西。
 *
 * **它不是流程图组件，也别往那个方向长。** 没有箭头、没有方框、没有底色、
 * 没有圆角 —— 阶段排成一行（窄屏落成一列），靠序号、留白和一条细线说明顺序；
 * 同一阶段里并排的条目本身就是「这几件事同时发生」。
 * 一旦开始给节点加框、连线和颜色，这一页就从「读数的地方」变成了稿子。
 */
export interface ProjectFlowStage {
  /**
   * 这一阶段的名字。渲染时前面会带上两位序号（01 / 02 …），
   * 序号由排版给，**不要写进这个字符串里**。
   */
  title: string
  /** 这一阶段里并排的几件事。只有一件就写一件 */
  items: { name: string; note?: string }[]
}

export interface ProjectFlow {
  /** 通路上方那行说明。位置与字号跟表的 caption 一致 */
  caption?: string
  stages: ProjectFlowStage[]
}

/** 详情页里的一小节 */
export interface ProjectBlock {
  /**
   * 引子，排在小节正文上方的一行。
   * 不写就是一段没有小标题的普通正文。
   */
  lead?: string
  /**
   * 这一节的分类小字，排在小节序号（01 / 02）后面、引子上方一行。
   * 写的是「这一节在讲什么」（性能优化 / 系统架构 / 服务化），不是标题 ——
   * 标题由 `lead` 承担。两行都写时，先看到分类，再看到标题。
   */
  kicker?: string
  text: string
  /**
   * 旁白：我自己补的一句话，比正文小一号、浅一档，缩进排在正文下面。
   * 简历里没有这一段 —— 全是「为什么这么做」，不是「做了什么」。
   */
  aside?: string
  /**
   * 并列的短句：流程、步骤、几件并排的事。一行一条，**不打序号**
   * （序号该是内容的一部分，写在句子里；行号由排版给，两套会打架）。
   */
  points?: string[]
  /**
   * 这一节自己的数字 —— 规模、条件、分项。
   *
   * 和项目级别的 `metrics` 分工：**`metrics` 是全页的结论**（排在页尾、
   * 独占一个「结果」小节），这里的是**叙述中间的一组数**，属于它所在的那一节。
   * 两者用的是同一套数字排法（大号数字在上、标签在下），所以同页出现不打架。
   */
  stats?: ProjectMetric[]
  /** 只有「数字必须对齐」时才用表格。能写成一段话的就别写成表 */
  table?: ProjectTable
  /** 只有「流向是内容本身」时才用通路，见 ProjectFlow 那段判据 */
  flow?: ProjectFlow
  /** 只有「不放就说不清」时才用视频，一页最多一段 */
  video?: ProjectVideo
}

/**
 * 一张表。
 *
 * **只在数字（或选项）需要纵向对齐时才用** —— 项目页是站上唯一「不手绘」的
 * 地方，一张表就是几条细线加几列字，不加底色、不加圆角，唯一的强调手段是
 * `highlight`：全表只有一行是实的，其余压到同一档透明度。
 */
export interface ProjectTable {
  /** 表上方那行说明。不写就直接出表 */
  caption?: string
  /** 表头。第一列是行名（左对齐），其余列右对齐 */
  head: string[]
  rows: string[][]
  /** 要突出的那一行（下标）。**全表只亮一行**，没有就不写 */
  highlight?: number
}

/** 结尾的量化结果。只放简历里真实存在的数字，不补充推算值。 */
export interface ProjectMetric {
  /** 数字部分 */
  value: string
  /** 单位，跟在数字后面 */
  unit?: string
  /** 这个数字说明什么 */
  label: string
}

export interface Project {
  /** 地址 /projects/:slug，也是唯一标识 */
  slug: string
  /** 完整项目名。列表页和详情页标题都用它 */
  name: string
  /** 展示用的起止时间 */
  period: string
  /** 只为排序，取结束月份，形如 2026.08 */
  end: string
  /** 我在项目里的角色 */
  role: string
  /** 关键字。列表页排成一行，详情页放在标题下面 */
  keywords: string[]
  /** 一句话摘要。列表页只显示这一句 */
  summary: string
  /**
   * 详情页的引言。**不写就用 `summary`** —— 列表页那一行放不下的长度
   * （要先把问题讲清楚，再进正文）就写在这里，列表页不受影响。
   */
  lede?: string
  /** 详情页正文 */
  blocks: ProjectBlock[]
  /** 结果数字，没有就留空 */
  metrics?: ProjectMetric[]
  /** 结果数字后面那句解释 */
  metricsNote?: string
  /**
   * 仓库链接与它的显示文字。
   *
   * ⚠️ **当前没有落点** —— 详情页那块外链 2026-09-19 删掉了（见 ProjectView.vue）。
   * 字段留着是因为它是真信息，不是忘了删；哪天真要再列出来，直接接回去就行。
   */
  href?: string
  hrefLabel?: string
}
